import {EventLogger} from 'gd-eventlog'
import { IIncyclistRoutesApi, RouteApiDescription, RouteApiDetail, RouteDescriptionQuery } from "./types";
import { AxiosInstance, AxiosRequestConfig } from "axios";
import { DEFAULT_DOMAIN, NO_CACHE, ROUTE_API } from './consts'
import { IncyclistRestApiClient } from '../../../api';
import { useUserSettings } from '../../../settings';
import { RoutePoint } from '../types';
import { Injectable } from '../../../base/decorators';
import { LatLng } from '../../../utils/geo';
import { IncyclistExternalRestApiClient } from '../../../api/rest/external';
import { isAllowedRedirectTarget } from '../../servers/validator';

const fixMissingRouteDistances = (points:Array<RoutePoint>) => {
    let routeDistance = 0
    points.forEach( (p)=> {
        if (!p.routeDistance)
            p.routeDistance = routeDistance
        routeDistance = p.routeDistance+p['distance']
    })
}

// verifies that the route does not contain the legacy format (poinst in decoded property)
const verify = (route)  => {
    if (route['decoded'] ) {
        route.points =route['decoded']
        delete route['decoded']

        fixMissingRouteDistances(route.points)
    }
}

// a request that never received an HTTP response (offline, DNS failure, connection refused, ...)
// TEMPORARY: a 504 (Gateway Timeout) is treated the same way. It is generated by an intermediary
// between the device and our servers (proxy, carrier or Wi-Fi gateway) and was never seen in the
// ingress access log, so it is a connectivity problem rather than a server error.
const isNoResponseError = (err): boolean => {
    return err?.message === 'Network Error' ||
        err?.code === 'ERR_NETWORK' ||
        err?.response?.status === 504 ||
        (err?.isAxiosError === true && !err.response)
}

/** the URL a response was finally served from (differs from the requested URL after a redirect) */
const getResponseUrl = (res): string | undefined => {
    return res?.request?.res?.responseUrl ?? res?.request?.responseURL
}

export const REDIRECT_NOT_ALLOWED = 'ERR_REDIRECT_NOT_ALLOWED'

export default class IncyclistRoutesApi implements IIncyclistRoutesApi { 

    protected logger: EventLogger
    protected api: AxiosInstance
    protected baseUrl?: string
    protected isExternal: boolean
    protected source?:string
    protected requestTimeout?:number
    protected enforceRedirectRules:boolean = false

    constructor(baseUrl?:string) {
        this.logger = new EventLogger('RouteListApi')
        this.baseUrl = baseUrl
        if (baseUrl) {
            this.isExternal = true
        }
    }

    setSource(source:string) {
        this.source = source
    }

    /**
     * Optional request controls for external servers
     *
     * @param props.timeout  request timeout in ms
     * @param props.enforceRedirectRules  if set, a response that was served from a URL that the route server
     *   address rules would refuse (e.g. redirect from https to http on the internet) is treated as failed
     */
    setRequestOptions(props:{timeout?:number, enforceRedirectRules?:boolean}) {
        this.requestTimeout = props.timeout
        this.enforceRedirectRules = props.enforceRedirectRules ?? false
    }

    protected logError( err:Error, fn:string, logInfo?) {
        const args = logInfo ?? {}
        this.logger.logEvent( {message:'Error', error:err.message, fn, ...args})
    }

    protected getApi():AxiosInstance {
        if (!this.api) {
            this.api = this.baseUrl ? 
                IncyclistExternalRestApiClient.getClient() :
                IncyclistRestApiClient.getClient()
            return this.api
        }
        return this.api
    }


     protected getBaseUrl() {
        if (this.baseUrl)
            return this.baseUrl.replace(/\/+$/,'')

        const domain = this.getUserSettings().getValue('DOMAIN',DEFAULT_DOMAIN)
        const defaultUrl = `https://dlws.${domain}/api/v1/routes`
        const baseUrl = this.getUserSettings().getValue(ROUTE_API,defaultUrl)
        return baseUrl
    }

    async getRouteDescriptions(query:RouteDescriptionQuery, throws:boolean = false): Promise<Array<RouteApiDescription>> {
        const {type='gpx',category} = query;

        let url  = (type === 'gpx' ) ? `?private=false` : `/?type=${type}`;
        if (category)
            url += `&category=${category}`

        try {
            const res = await this._get( url, NO_CACHE )      
            if (this.isExternal && Array.isArray(res.data)) {
                res.data.forEach( route => {
                    route.apiServer = this.source
                })                
            }
            return res.data;           
        }
        catch(err) {
            if (throws)
                throw(err)

            this.logError(err,'getRouteDescriptions', {query})
            return undefined
        }
    }


    async getRouteDetails( routeId: string): Promise<RouteApiDetail> {

        try {
            const res = await this._get( `/${routeId}` )  
            verify(res.data)
            return res.data;           
        }
        catch {
            return undefined
        }
    }

    async getRoutePreview( routeId: string): Promise<string> {

        try {
            const res = await this._get( `/${routeId}/preview` )              
            return res.data?.url;           
        }
        catch {
            return undefined
        }
    }

    async getCountry(query:LatLng|Array<LatLng>):Promise<string|undefined> {

        if (this.isExternal)
            return

        if (!query)
            return

        let url;
        if (Array.isArray(query)) {
            const points = query.slice(0,100).map( (p:LatLng) => `${p.lat},${p.lng}` ).join(';')
            url = `/country?points=${points}`
        }
        else {
            const {lat,lng} = query            
            url = `/country?lat=${lat}&lng=${lng}`
        }

        
        try {

            const conf: AxiosRequestConfig = {};
            conf.validateStatus = (status: number) => {
                return (status >= 200 && status < 300) || status == 404 || status==429
            }

            const res = await this._get(url,conf ) 
            if (res.status===404)
                return;
            if (res.status===429) {
                this.logger.logEvent({message:'getCountry hit rate limit',query})
                return;
            }
            
            return res.data.country?.toUpperCase()
        }
        catch(err) {
            if (isNoResponseError(err)) {
                // device is offline or server not reachable - not an application error
                this.logger.logEvent({message:'getCountry failed: no response from server', reason:err.message})
                return
            }
            this.logError(err,'getCountry')
        }

    }



    async reload():Promise<void> {
        if (this.isExternal)
            return

        try {
            await this._get( `/reload` )                   
        }
        catch(err) {
            this.logError(err,'reload')
        }

    }

    protected async _get(url:string, ...args) {
        const api = this.getApi()
        const baseUrl = this.getBaseUrl()
        const requestUrl = baseUrl+url

        if (this.requestTimeout!==undefined) {
            args = [ {...(args[0]??{}), timeout:this.requestTimeout}, ...args.slice(1)]
        }

        const res = await api.get( requestUrl, ...args )
        this.verifyRedirect(requestUrl, res)
        return res
    }

    protected verifyRedirect(requestUrl:string, res) {
        if (!this.isExternal || !this.enforceRedirectRules)
            return

        const finalUrl = getResponseUrl(res)
        if (!finalUrl || finalUrl===requestUrl)
            return

        if (!isAllowedRedirectTarget(finalUrl)) {
            this.logger.logEvent({message:'redirect refused', source:this.source})
            throw Object.assign( new Error('redirect not allowed'), {code:REDIRECT_NOT_ALLOWED})
        }
    }


    @Injectable
    getUserSettings() {
        return useUserSettings()
    }


}




